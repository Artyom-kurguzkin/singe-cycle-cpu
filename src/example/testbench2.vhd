stimulus:process --no sensitivity list since using wait statements
variable a_int:integer range 0 to 15;
variable b_int:integer range 0 to 15;
variable s_int:integer range 0 to 15;

begin
  s_calc<= "0000";
  wait for 10 ns; --initial startup time
  --test basic adder functions and flags 
  a<="0000";
  b<="0000";
  opcode<="000";
  wait for 5 ns;  --allow time for the signals to propogate
    assert s = "0000"  --test for correctness
      report "incorrect basic adder output"
      severity FAILURE;		
	 assert zero='1'
      report "incorrect zero output"
      severity FAILURE;
	 assert overflow='0'
      report "incorrect overflow output"
      severity FAILURE;


  a<="0001";
  b<="0000";
  opcode<="000";
  wait for 5 ns;
    assert s = "0001"
      report "incorrect basic adder output"
      severity FAILURE;		
	 assert zero='0'
      report "incorrect zero output"
      severity FAILURE;

  --test adder functionality
  --this section uses for loops to produce all possible combinations of the
  --input vectors
  --the results of the ALU are then compared with the values generated by 
  --integer math
  opcode<="000";  
  for a_int in 0 to 15 loop
    for b_int in 0 to 15 loop
		a<=CONV_STD_LOGIC_VECTOR(a_int,4);
		b<=CONV_STD_LOGIC_VECTOR(b_int,4);
		s_calc<= CONV_STD_LOGIC_VECTOR(a_int+b_int,4);
		wait for 4 ns;
      assert s = s_calc
        report "incorrect adder output "
        severity FAILURE;		
	 end loop;
  end loop;
  
  
  --test subtraction
  opcode<="001";  
  for a_int in 0 to 15 loop
    for b_int in 0 to 15 loop
		a<=CONV_STD_LOGIC_VECTOR(a_int,4);
		b<=CONV_STD_LOGIC_VECTOR(b_int,4);
		s_calc<= CONV_STD_LOGIC_VECTOR(a_int-b_int,4);
		wait for 3 ns;
      assert s = s_calc
        report "incorrect subtractor output "
        severity FAILURE;		
	 end loop;
  end loop;
  
  --test and - only four possible combinations
  opcode<="010";  
  a<="1100";
  b<="1010";
  opcode<="010";
  wait for 3 ns;
    assert s = "1000"
      report "incorrect and output"
      severity FAILURE;		
  		
  --test or - only four possible combinations
  opcode<="010";  
  a<="1100";
  b<="1010";
  opcode<="011";
  wait for 3 ns;
    assert s = "1110"
      report "incorrect or output"
      severity FAILURE;			
	
  --test xor
  a<="1100";
  b<="1010";
  opcode<="100";
  wait for 3 ns;
    assert s = "0110"
      report "incorrect xor output"
      severity FAILURE;

  a<="1111";
  b<="0000";
  opcode<="100";
  wait for 3 ns;
    assert s = "1111"
      report "incorrect xor output"
      severity FAILURE;

  --test invert (not a, b is ignored)
  a<="1010";
  b<="0000";
  opcode<="101";
  wait for 3 ns;
    assert s = "0101"
      report "incorrect invert output"
      severity FAILURE;

  a<="0000";
  b<="1111";
  opcode<="101";
  wait for 3 ns;
    assert s = "1111"
      report "incorrect invert output"
      severity FAILURE;

  --test increment
  a<="0000";
  b<="0000";
  opcode<="111";
  wait for 3 ns;
    assert s = "0001"
      report "incorrect increment output"
      severity FAILURE;
    assert overflow='0'
      report "incorrect overflow on increment"
      severity FAILURE;

  a<="0111";
  b<="0000";
  opcode<="111";
  wait for 3 ns;
    assert s = "1000"
      report "incorrect increment output"
      severity FAILURE;

  --increment wraps around with unsigned overflow
  a<="1111";
  b<="0000";
  opcode<="111";
  wait for 3 ns;
    assert s = "0000"
      report "incorrect increment wrap output"
      severity FAILURE;
    assert overflow='1'
      report "incorrect overflow on increment wrap"
      severity FAILURE;

  --test twos complement overflow - the following adds seven to one 
  --which should trigger an overflow
  a<="0111";
  b<="0001";
  opcode<="000";
  wait for 3 ns;  --allow time for the signals to propogate
	 assert compl_overflow='1'
      report "incorrect twos complement overflow output"
      severity FAILURE;
	 assert overflow='0'
      report "incorrect overflow output"
      severity FAILURE;
	
  --this adds minus one to minus one which should not
  --cause a twos complement overflow  
  a<="1111";
  b<="1111";
  opcode<="000";
  wait for 3 ns;  --allow time for the signals to propogate
	 assert compl_overflow='0'
      report "incorrect twos complement overflow output"
      severity FAILURE;	
    assert overflow='1'
      report "incorrect overflow output"
      severity FAILURE;
	
  
  assert false --inform the user that the testbench is complete
    report "testbench complete"
    severity note;		

  wait; --terminate the testbench process
